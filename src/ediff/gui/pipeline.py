"""
pipeline.py — EDIFF workflow logic, decoupled from the GUI.

Uses ediff's own API exactly as documented in the source code.
All plotting is done by capturing ediff/matplotlib output into figures.
"""

import os
import sys
import json
import threading
import subprocess
import matplotlib
matplotlib.use("Agg", force=True)   # non-interactive backend
import matplotlib.pyplot as plt
plt.show = lambda *a, **k: None

import numpy as np
from pathlib import Path
import io as _io


def _capture_fig():
    """
    Capture the current matplotlib figure as a PNG buffer.

    This helper grabs the currently active matplotlib figure, saves
    it into an in-memory PNG buffer, closes the figure, and returns
    the buffer. It is useful when plots are generated by pipeline
    methods and need to be embedded into GUI result cards without
    writing temporary image files to disk.

    Returns
    -------
    io.BytesIO
        In-memory PNG buffer positioned at the beginning.
    """
    # Get the current active matplotlib figure.
    fig = plt.gcf()

    # Create an in-memory binary buffer instead of saving
    # to a file.
    buf = _io.BytesIO()

    # Save the figure as PNG using the figure's current DPI.
    # bbox_inches='tight' trims unnecessary whitespace around
    # the plot.
    fig.savefig(
        buf,
        format="png",
        dpi=fig.get_dpi(),
        bbox_inches="tight",
    )

    # Rewind the buffer so readers can consume it from the beginning.
    buf.seek(0)

    # Close the figure to avoid accumulating hidden matplotlib
    # figures in memory.
    plt.close(fig)

    return buf


class EdiffPipeline:
    """
    Stateful wrapper around the EDIFF processing workflow.

    The GUI uses this class as the backend pipeline object.
    It stores the current working directory, loaded structure/XRD
    data, loaded ELD image, background subtraction result,
    and a persistent subprocess used for interactive/manual
    operations.

    The persistent worker is used for operations that require user
    interaction, such as ellipse correction, manual center detection,
    and interactive background point picking. Keeping one worker
    alive avoids repeatedly paying the import/startup cost of heavy
    scientific libraries.
    """

    def __init__(self, workdir: Path):
        """
        Initialize the EDIFF pipeline state.

        Parameters
        ----------
        workdir : pathlib.Path
            Directory where pipeline outputs should be written.

        Notes
        -----
        The constructor also tries to pre-warm the persistent
        interactive worker in the background. This is best-effort:
        failure during pre-warming is ignored because the worker
        can still be spawned later on demand.
        """
        # Normalize and store the working directory as a Path object.
        self.workdir = Path(workdir)

        # Import the main ediff package lazily here and store it
        # on the pipeline. This keeps all backend access grouped
        # through self.ed.
        import ediff as ed
        self.ed = ed

        # Paths related to the currently loaded ELD image.
        self._eld_path          = None
        self._original_eld_path = None   # set before ellipse correction

        # Calculated theoretical XRD patterns, one object per loaded
        # structure.
        self.xrd_list  = []    # list of XRD_polycrystal objects

        # Loaded experimental electron diffraction image.
        self.eld = None  # ELD_polycrystal object

        # Background subtraction result/state object.
        self.smet = None

        # ── Persistent interactive-worker state ──────────────────────────
        # One long-lived subprocess handles all manual/interactive
        # operations for the lifetime of the app:
        # - ellipse correction;
        # - manual center detection;
        # - interactive background point picking.
        # This avoids spawning a new Python process and re-importing
        # large dependencies such as numpy, scipy, skimage, cv2, matplotlib,
        # and ediff every time the user clicks an interactive button.

        self._worker_proc = None        # persistent worker Popen object
        self._worker_stdin = None       # worker stdin, text mode
        self._worker_stdout = None      # worker stdout, text mode
        self._worker_req_id = 0         # monotonically increasing request id
        self._worker_stderr_lines = []  # recent stderr lines for diagnostics

        # Lock protecting worker process handles and stderr diagnostics.
        # This matters because the GUI thread and background worker threads
        # may access the persistent subprocess state at the same time.
        self._proc_lock     = threading.Lock()

        # Pre-warm the persistent interactive worker in the background.
        # This starts the subprocess early, before the user reaches
        # an interactive operation. The constructor does not wait for
        # the worker's heavy imports to finish, so this usually does
        # not noticeably slow GUI startup. By the time the user clicks
        # an interactive step, the worker may already be ready.
        try:
            self._ensure_worker()

        except Exception:
            # Best-effort only.
            # If pre-warming fails, a later call to _call_worker() /
            # _ensure_worker() will try again and surface the real error
            # in the context of the interactive operation.
            pass


    # ── Persistent interactive-worker management ────────────────────────────
    def terminate_subprocess(self):
        """
        Terminate the persistent interactive worker process, if it is running.

        This method is the low-level "Abort" action for whatever manual or
        interactive operation is currently in progress. It clears the stored
        process handles under a lock, then terminates or kills the subprocess.

        Thread safety
        -------------
        This method can be called from the main GUI thread while another
        background thread is blocked inside ``_call_worker()`` waiting for a
        worker response. The lock ensures that worker handles are read and
        cleared consistently.

        Notes
        -----
        Because the worker is persistent, killing it does not permanently
        disable interactive functionality. The next interactive operation will
        transparently spawn a fresh worker through ``_ensure_worker``.

        Returns
        -------
        None
        """
        # Clear process handles while holding the lock so no other thread
        # sees a partially reset worker state.
        with self._proc_lock:
            proc = self._worker_proc
            self._worker_proc   = None
            self._worker_stdin  = None
            self._worker_stdout = None

        # If a process existed and is still running, try graceful
        # termination.
        if proc is not None and proc.poll() is None:
            proc.terminate()

            try:
                # Give the worker a short chance to exit cleanly.
                proc.wait(timeout=3)

            except Exception:
                # If graceful termination fails or times out, force-kill it.
                try:
                    proc.kill()
                except Exception:
                    pass

    def _resolve_launch_cmd(self, module_name):
        """
        Build the subprocess launch command for a GUI helper module.

        The app can run in two different contexts:

        1. Frozen/PyInstaller build
           Launch a companion executable, for example
           ``interactive_worker.exe``, located next to the main executable
           or inside the PyInstaller internal directory.

        2. Normal Python installation/source checkout
           Launch the module using ``python -m ediff.gui.<module_name>``.
           This lets Python resolve the module through the normal import
           system.

        Parameters
        ----------
        module_name : str
            Name of the helper module to launch, without package prefix.
            Example: ``"interactive_worker"``.

        Returns
        -------
        tuple
            ``(cmd, cwd)``, where ``cmd`` is a list suitable for
            ``subprocess.Popen`` and ``cwd`` is either a working directory
            string or None.

        Raises
        ------
        RuntimeError
            If running frozen and the companion executable cannot be found.
        """
        if getattr(sys, 'frozen', False):
            # Frozen application:
            # look for a bundled helper executable.
            exe_name = f'{module_name}.exe'
            exe_dir  = Path(sys.executable).parent

            # PyInstaller layouts can differ depending on build options,
            # so search the common possible locations.
            candidates = [
                exe_dir / '_internal' / exe_name,
                exe_dir / exe_name,
                Path(sys._MEIPASS) / exe_name,
            ]

            exe_path = next((p for p in candidates if p.exists()), None)

            if exe_path is None:
                searched = '\n  '.join(str(p) for p in candidates)
                raise RuntimeError(
                    f'Bundled executable not found. Searched:\n  {searched}\n'
                    f'Rebuild the application with build.bat.')
            # Launch the executable directly and use its parent as cwd.
            return [str(exe_path)], str(exe_path.parent)
        else:
            # Normal Python execution:
            # run the module using the current interpreter.
            return ([
                sys.executable,
                '-m',
                f'ediff.gui.{module_name}'
            ],
                    None
            )

    def _drain_worker_stderr(self, proc):
        """
        Continuously drain stderr from the interactive worker process.

        The interactive worker redirects verbose messages, progress output,
        and tracebacks to stderr. This method runs in a background daemon
        thread and continuously reads that stream.

        Why this is necessary
        ---------------------
        OS pipes have finite buffers. If stderr is never read and the worker
        writes enough output, the pipe can fill up. The worker would then
        block while trying to write to stderr, causing the main app to wait
        forever for a stdout response that will never arrive.

        The method also keeps the most recent stderr lines so that worker
        startup failures or crashes can be diagnosed and shown to the user.

        Parameters
        ----------
        proc : subprocess.Popen
            Worker process whose stderr stream should be drained.

        Returns
        -------
        None
        """

        try:
            # Iterate over stderr until the stream closes.
            for line in proc.stderr:
                # Forward worker stderr to this process's stderr for developer
                # visibility when running from a terminal.
                sys.stderr.write(f'[interactive_worker] {line}')
                sys.stderr.flush()

                # Keep the most recent stderr lines for diagnostics.
                with self._proc_lock:
                    self._worker_stderr_lines.append(line)

                    # Keep only the last 200 lines to avoid unbounded growth.
                    del self._worker_stderr_lines[:-200]

        except Exception:
            # The pipe may already be closed or the process may have exited.
            # Nothing else is needed in that case.
            pass

    def _spawn_worker(self):
        """
        Launch the persistent interactive-worker subprocess.

        This method starts the helper process, stores its stdin/stdout
        handles, resets request/diagnostic state, and starts a daemon
        thread that drains stderr.

        Important
        ---------
        This method must be called with ``self._proc_lock`` already held.

        Returns
        -------
        None

        Raises
        ------
        RuntimeError
            If the worker process cannot be launched because the executable
            or Python module is missing, blocked, or inaccessible.
        """
        # Resolve command and launch directory for the current runtime context.
        full_cmd, launch_cwd = self._resolve_launch_cmd('interactive_worker')

        # Ensure UTF-8 text I/O in the worker regardless of system locale.
        env = os.environ.copy()
        env['PYTHONIOENCODING'] = 'utf-8'
        env['PYTHONUTF8']       = '1'

        try:
            # Start the worker in text mode with line buffering.
            # stdin/stdout/stderr are all piped because communication happens
            # through these streams.
            proc = subprocess.Popen(
                full_cmd,
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                env=env,
                cwd=launch_cwd,
                text=True,
                bufsize=1,
                encoding='utf-8',
                errors='replace'
            )

        except (FileNotFoundError, PermissionError, OSError) as e:
            # Convert OS-level launch problems into a clearer user-facing
            # error. Common causes include missing bundled exe, antivirus
            # quarantine, incomplete installation, or unreadable install
            # directory.

            raise RuntimeError(
                f'Could not start interactive worker ({full_cmd[0]})\n'
                f'({type(e).__name__}: {e})\n\n'
                f'This usually means the file is missing, was quarantined by '
                f'antivirus software, or the installation is incomplete. '
                f'Try reinstalling, or check your antivirus quarantine.')

        # Store live worker handles.
        self._worker_proc   = proc
        self._worker_stdin  = proc.stdin
        self._worker_stdout = proc.stdout

        # Reset per-worker request and diagnostic state.
        self._worker_req_id = 0
        self._worker_stderr_lines = []

        # Start stderr-draining thread immediately to avoid deadlocks.
        threading.Thread(
            target=self._drain_worker_stderr,
            args=(proc,),
            daemon=True
        ).start()

    def _ensure_worker(self):
        """
        Ensure that the persistent interactive worker process is running.

        This method is safe to call before every interactive operation.
        If a healthy worker already exists, it does nothing. If the worker
        is missing, has exited, was killed by Abort, or crashed, it starts
        a fresh one.

        Returns
        -------
        None
            Leaves ``self._worker_proc`` pointing to a live subprocess.
        """
        # Access to the process handle must be locked because Stop/Abort
        # can terminate the worker while another thread is trying to use it.
        with self._proc_lock:
            proc = self._worker_proc

            # If the worker exists and has not exited, it is ready to use.
            if proc is not None and proc.poll() is None:
                return

            # Otherwise spawn a new persistent worker.
            self._spawn_worker()

    def _call_worker(self, op, kwargs):
        """
        Send one request to the persistent interactive worker and wait
        for a reply.

        The interactive worker is a long-lived subprocess used for manual
        or interactive operations, such as ellipse correction, manual
        center detection, and interactive background subtraction. Requests
        are sent as one-line JSON messages through stdin, and responses are
        read as one-line JSON messages from stdout.

        Each request receives a monotonically increasing request ID.
        The response must contain the same ID; stale or mismatched responses
        are ignored.

        Parameters
        ----------
        op : str
            Operation name understood by the interactive worker.

        kwargs : dict
            Keyword arguments sent to the worker for the requested operation.

        Returns
        -------
        object
            The ``result`` field from the worker response.

        Raises
        ------
        RuntimeError
            Raised with ``"__CANCELLED__"`` if the worker was deliberately
            killed while this request was pending. Also raised if the worker
            exits unexpectedly or reports an operation error.
        """
        # Make sure there is a live worker process before sending
        # the request.
        self._ensure_worker()

        # Reserve a unique request ID and copy the current worker handles
        # while holding the process lock.
        # The actual blocking read is done outside the lock so Stop/Abort
        # can still acquire the lock and terminate the worker if needed.
        with self._proc_lock:
            self._worker_req_id += 1
            req_id = self._worker_req_id
            stdin  = self._worker_stdin
            stdout = self._worker_stdout
            proc   = self._worker_proc

        try:
            # Send exactly one JSON request line to the worker.
            # Newline is the message delimiter.
            stdin.write(
                json.dumps(
                    {"id": req_id, "op": op, "kwargs": kwargs}
                ) + "\n"
            )
            stdin.flush()

        except (BrokenPipeError, OSError):
            # The worker died or was killed exactly while sending
            # the request. Treat this as cancellation so GUI callers
            # can handle it uniformly.
            raise RuntimeError('__CANCELLED__')

        # Wait for the matching response line.
        while True:
            line = stdout.readline()
            if not line:
                # EOF means the worker's stdout closed.
                # Usually this means the worker exited. A process can
                # close its pipes slightly before proc.poll() reports
                # the final return code, so wait briefly to get a reliable
                # code.
                try:
                    returncode = proc.wait(timeout=2)
                except subprocess.TimeoutExpired:
                    returncode = proc.poll()

                # Negative return code means terminated by signal/killed.
                # Treat as cancellation, usually caused by terminate_subprocess().
                if returncode is not None and returncode < 0:
                    raise RuntimeError('__CANCELLED__')

                # Include recent worker stderr in the error message. This often
                # contains the real traceback from worker startup/import/runtime
                # failure.
                with self._proc_lock:
                    detail = ''.join(self._worker_stderr_lines[-40:]).strip()

                msg = ('Interactive worker exited unexpectedly '
                       f'(return code {returncode}).')

                if detail:
                    msg += f'\n\n--- worker stderr (most recent) ---\n{detail}'
                raise RuntimeError(msg)

            # Remove whitespace/newline around the protocol line.
            line = line.strip()

            # Ignore empty stdout lines.
            if not line:
                continue

            try:
                resp = json.loads(line)

            except json.JSONDecodeError:
                # Ignore stray non-protocol stdout output.
                # Ideally the worker should send all diagnostics to stderr,
                # but this makes the protocol more robust if some external
                # library prints to stdout unexpectedly.
                continue  # stray non-protocol output on stdout — ignore

            # Ignore responses that do not match this request.
            # This protects against stale/mismatched messages.
            if resp.get("id") != req_id:
                continue

            if resp.get("ok"):
                # Successful response.
                return resp.get("result")

            # Worker returned a structured error.
            raise RuntimeError(resp.get("error") or
                                'Interactive worker reported an error.')

    # ── Step 0 ────────────────────────────────────────────────────────────────
    def set_plot_params(self, size=(10, 5), fontsize=8, dpi=120):
        """
        Set global plotting parameters used by EDIFF plotting utilities.

        This is a thin wrapper around ``ediff.io.Plots.set_plot_params``.
        It lets the GUI/backend pipeline standardize figure size, font
        size, and DPI before creating plot buffers.

        Parameters
        ----------
        size : tuple, optional
            Matplotlib figure size in inches, passed to EDIFF plotting
            utilities.

        fontsize : int or float, optional
            Default font size for generated plots.

        dpi : int or float, optional
            Figure resolution in dots per inch.

        Returns
        -------
        None
            Updates global/default plotting parameters in the EDIFF
            plotting layer.
        """
        # Delegate the actual setting to EDIFF's plotting helper.
        self.ed.io.Plots.set_plot_params(
            size=size,
            fontsize=fontsize,
            dpi=dpi
        )

    # ── Step 2: XRD ───────────────────────────────────────────────────────────
    def calculate_xrd(self, cif_paths, wavelength, two_theta_range,
                      peak_profile_sigma, temp_factors=0.8,
                      peak_profile='pseudo_voigt'):
        """
        Calculate theoretical XRD diffractograms from selected structure
        files.

        For each input structure file, this method creates one
        ``XRD_polycrystal`` object and stores it in ``self.xrd_list``.
        The resulting diffractograms are later plotted and compared
        with the calibrated ELD profile.

        Parameters
        ----------
        cif_paths : sequence of str or pathlib.Path
            Paths to structure files. Each file produces one XRD
            reference phase.

        wavelength : float
            X-ray/electron wavelength used for theoretical diffraction
            calculation, in Å.

        two_theta_range : tuple
            ``(min, max)`` two-theta range in degrees.

        peak_profile_sigma : float
            Peak-width parameter passed to the selected peak-profile
            function.

        temp_factors : float, optional
            Temperature factor passed to the XRD calculation.

        peak_profile : str, optional
            Name of the peak profile to use. Supported values are
            ``"pseudo_voigt"``, ``"gaussian"``, and ``"lorentzian"``.
            Unknown values fall back to ``"pseudo_voigt"``.

        Returns
        -------
        None
            Populates ``self.xrd_list``.

        Raises
        ------
        ValueError
            If a calculated diffractogram contains no finite q values.
        """
        import ediff.pcryst as pcryst

        # Map GUI/profile string names to actual backend peak-profile
        # functions.
        profile_map = {
            'pseudo_voigt': pcryst.PeakProfiles.pseudo_voigt,
            'gaussian':     pcryst.PeakProfiles.gaussian,
            'lorentzian':   pcryst.PeakProfiles.lorentzian,
        }

        # Use pseudo-Voigt as the robust default if an unknown profile
        # string is passed in.
        profile_fn = profile_map.get(
            peak_profile,
            pcryst.PeakProfiles.pseudo_voigt
        )

        # Replace any previous XRD results with this new calculation.
        self.xrd_list = []

        for cif in cif_paths:
            # Backend expects integer two-theta limits.
            tt = (
                int(two_theta_range[0]),
                int(two_theta_range[1])
            )

            # Build one theoretical polycrystal diffractogram
            # for this structure.
            xrd = self.ed.pcryst.XRD_polycrystal(
                description=Path(cif).stem,
                structure=str(cif),
                wavelength=float(wavelength),
                two_theta_range=tt,
                peak_profile_sigma=float(peak_profile_sigma),
                temp_factors=float(temp_factors),
                peak_profile=profile_fn,
            )

            # Basic sanity check: the calculated q array should contain
            # at least one finite value. If not, later plotting/calibration
            # would be meaningless.
            q = np.array(
                xrd.diffractogram['q'].values,
                dtype=float
            )

            if not np.any(np.isfinite(q)):
                raise ValueError(
                    f"XRD calculation produced no valid data for {Path(cif).name}. "
                    f"Check the CIF file and wavelength/2theta parameters."
                )

            # Store this reference phase.
            self.xrd_list.append(xrd)

    def plot_xrd(self, xlim=None, ylim=None):
        """
        Plot calculated XRD diffractograms and return them as PNG buffers.

        One plot is generated for each item in ``self.xrd_list``. The method
        uses EDIFF's own ``Diffractogram1D.show`` method, then optionally
        applies axis limits before capturing each matplotlib figure into
        a ``BytesIO`` PNG buffer.

        Parameters
        ----------
        xlim : tuple or None, optional
            q-axis limits passed to ``plt.xlim`` if provided.

        ylim : tuple or None, optional
            intensity-axis limits passed to ``plt.ylim`` if provided.

        Returns
        -------
        list of io.BytesIO
            One PNG buffer per XRD reference phase.
        """
        bufs = []
        for xrd in self.xrd_list:
            # Use ediff's native diffractogram plotting helper.
            # It sets labels, grid, and layout consistently with
            # the rest of ediff.
            xrd.diffractogram.show(
                X='q',
                Y='I',
                Xlabel=r'q [1/Å]',
                Ylabel='Intensity',
            )
            # Apply optional remembered/user-specified axis limits.
            if xlim: plt.xlim(xlim)
            if ylim: plt.ylim(ylim)

            # Capture the current figure as a PNG buffer and close it.
            bufs.append(_capture_fig())
        return bufs

    # ── Step 3: ELD load + optional ellipse correction ────────────────────────
    def load_eld(self, eld_path):
        """
        Load the experimental 2D electron diffraction pattern.

        This initializes the pipeline's ELD state from a raw
        diffraction image file. The method also records three
        path variables used by later ellipse-correction logic:
            - ``self._eld_path``
              Current active ELD image path. This may later point
              to the corrected image.
            - ``self._original_eld_path``
              Original image path before ellipse correction.
            - ``self._raw_eld_path``
              True raw image path. This is set only on fresh ELD
              loading and should not be modified by ellipse
              correction attempts.

        Parameters
        ----------
        eld_path : str or pathlib.Path
            Path to the experimental 2D diffraction image.

        Returns
        -------
        None
            Loads ``self.eld`` as an ``ELD_polycrystal`` object
            and updates internal ELD path tracking.
        """
        # Current active ELD path starts as the selected raw image.
        # Later, after ellipse correction, this may become
        # ellipse_corrected.png.
        self._eld_path = str(eld_path)

        # Store the original path before any correction is applied.
        self._original_eld_path = str(eld_path)

        # Store the true raw image path.
        # This is deliberately separate from _eld_path because _eld_path
        # changes after ellipse correction. Every correction retry should
        # start from this raw image rather than from a previous corrected
        # output.
        self._raw_eld_path      = str(eld_path)

        # Create the ELD object from the raw 2D diffractogram.
        self.eld = self.ed.pcryst.ELD_polycrystal(
            description="ELD experiment",
            diffractogram2D=str(eld_path),
        )


    def reset_to_raw_eld(self):
        """
        Reload the ELD object from the true raw diffraction image.

        This discards the currently active ELD object, which may
        contain a previous ellipse-corrected image, and reloads
        the original raw diffraction pattern stored in `
        `self._raw_eld_path``.

        This should be called before starting a new ellipse-correction
        attempt so hat repeated attempts do not compound distortions
        from previous, possibly bad, point selections.

        Returns
        -------
        None
            Replaces ``self.eld`` with a fresh raw-image ELD object
            and resets ``self._eld_path`` to ``self._raw_eld_path``.
        """
        # Recreate the ELD object from the true raw file.
        self.eld = self.ed.pcryst.ELD_polycrystal(
            description='ELD experiment',
            diffractogram2D=self._raw_eld_path,
        )

        # The active ELD path is now again the raw image.
        self._eld_path = self._raw_eld_path

    def correct_ellipse(self, icut=200, cmap='gray'):
        """
        Correct elliptical distortion in the ELD image using
        the interactive worker. The correction always starts from
        ``self._raw_eld_path``, not from the currently active ELD
        image. This prevents repeated correction attempts from
        compounding errors.

        The interactive worker writes a corrected image file into
        the working directory as ``ellipse_corrected.png``. After
        successful correction, this method reloads that corrected
        image as the active ``ELD_polycrystal`` object.

        Parameters
        ----------
        icut : int or float, optional
            Intensity cutoff used for displaying/selecting points
            in the interactive correction window.

        cmap : str, optional
            Matplotlib colormap used in the interactive correction
            window.

        Returns
        -------
        None
            Updates ``self.eld`` and ``self._eld_path`` to the corrected
            image.

        Raises
        ------
        RuntimeError
            If the interactive worker fails or if the corrected image
            file is not written.
        """
        # Remember that the original image before correction is the true
        # raw image.
        self._original_eld_path = self._raw_eld_path

        # Output path for the corrected image.
        corrected_path = str(self.workdir / 'ellipse_corrected.png')

        # Ask the persistent interactive worker to perform ellipse
        # correction.
        # The worker handles the interactive matplotlib/Qt point
        # selection and writes the corrected image to corrected_path.
        self._call_worker(
            'ellipse',
            dict(
                eld_path=self._raw_eld_path,
                icut=icut,
                cmap=cmap,
                out_path=corrected_path,
            ),
        )

        # _call_worker raises on failure. If we get here, the worker
        # reported success, but still verify that the expected output
        # file exists.
        if not Path(corrected_path).exists():
            raise RuntimeError('Corrected image file was not written.')

