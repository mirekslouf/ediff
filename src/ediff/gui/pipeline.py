    def plot_ellipse_diff(self, icut=200, cmap='hot', xlim=None, ylim=None):
        """
        Plot the absolute difference between raw and ellipse-corrected
        ELD images. This produces a diagnostic image:

        ``abs(raw - corrected)``

        It is useful when the correction is visually subtle and the
        before/after plots look nearly identical. Brighter pixels indicate
        regions that changed more during ellipse correction.

        Because ellipse correction may pad or resize the image, the raw and
        corrected images are center-cropped to their common overlap before
        subtraction.

        Parameters
        ----------
        icut : int or float, optional
            Maximum displayed difference value. The difference image is
            clipped to ``[0, icut]`` before plotting.

        cmap : str, optional
            Matplotlib colormap used for the difference image. ``"hot"``
            is useful for visualizing magnitude.

        xlim : tuple or None, optional
            Optional x-axis pixel limits.

        ylim : tuple or None, optional
            Optional y-axis pixel limits.

        Returns
        -------
        io.BytesIO
            PNG buffer containing the absolute-difference image.
        """
        # Load the true raw image and currently active image as float
        # arrays. The active image is expected to be the ellipse-corrected
        # image.
        raw_img = self.ed.io.Diffractogram2D(
            self._raw_eld_path
        ).astype(
            float
        )
        corrected_img = self.ed.io.Diffractogram2D(
            self._eld_path
        ).astype(
            float
        )

        # The corrected image may be padded or square while the raw image
        # may have  its original rectangular size. Use the common centered
        # overlap.
        h = min(raw_img.shape[0], corrected_img.shape[0])
        w = min(raw_img.shape[1], corrected_img.shape[1])

        def _center_crop(img, h, w):
            """
            Return the centered crop of ``img`` with shape
            ``(h, w)``.

            Parameters
            ----------
            img : ndarray
                Input 2D image.

            h : int
                Target crop height.

            w : int
                Target crop width.

            Returns
            -------
            ndarray
                Center-cropped image.
            """
            # Compute top-left corner of the centered crop.
            y0 = (img.shape[0] - h) // 2
            x0 = (img.shape[1] - w) // 2

            return img[y0:y0 + h, x0:x0 + w]

        # Compute absolute difference on the common centered overlap.
        diff = np.abs(_center_crop(raw_img, h, w) -
                      _center_crop(corrected_img, h, w))

        # Plot the difference image.
        plt.figure(figsize=(6, 6))
        im = plt.imshow(
            np.clip(
                diff,
                0,
                icut
            ),
            cmap=cmap,
            origin='upper'
        )
        plt.title("Absolute difference (Before vs After)")
        plt.colorbar(im, label="|Before - After|")
        plt.gca().grid(False)

        # Apply optional pixel-axis limits.
        if xlim: plt.xlim(xlim)
        if ylim: plt.ylim(ylim)

        # Capture the current figure and close it.
        return _capture_fig()

    # ── Step 4: Center detection ───────────────────────────────────────────────
    def find_center(self, detection, refinement, icut,
                    in_file=None, out_file=None, cmap='gray',
                    csquare=50, cintensity=0.8, rtype=1,
                    heq=False, sobel=False, masking=True,
                    normalize_bg=False, live_plot=False
                    ):
        """
        Find the center of the currently loaded 2D ELD diffractogram.

        The method supports both fully automatic center detection and
        interactive manual workflows.

        Automatic methods run directly in the current process through
        ``self.eld.find_center``. Manual detection or manual refinement
        is routed  through the persistent interactive worker subprocess,
        because those methods open interactive matplotlib/Qt windows and
        should not run inside the GUI worker thread directly.

        Parameters
        ----------
        detection : object or str or None
            Detection method passed to EDIFF. If ``None``, the center
            is read from ``in_file``. If ``"manual"``, the interactive
            worker is used.

        refinement : object or str or None
            Refinement method passed to EDIFF. If ``"manual"``,
            the interactive worker is used.

        icut : int or float
            Intensity cutoff used for center detection and plotting.

        in_file : str or pathlib.Path or None, optional
            Path to an existing center file, used when reading center
            coordinates from file.

        out_file : str or pathlib.Path or None, optional
            Path where detected center coordinates should be written.

        cmap : str, optional
            Colormap used by plotting/interactive routines.

        csquare : int or float, optional
            Size of the square region used by center-detection/detail
            routines.

        cintensity : float, optional
            Relative intensity threshold used by some automatic center-
            detection methods.

        rtype : int, optional
            Ring/type parameter passed to the backend center finder.

        heq : bool, optional
            Whether histogram equalization should be used.

        sobel : bool, optional
            Whether Sobel filtering should be used.

        masking : bool, optional
            Whether masking should be used.

        Returns
        -------
        None
            Updates ``self.eld.center`` in place and optionally writes
            a center file.
        """
        # Manual detection/refinement needs an interactive GUI window.
        # Those operations are delegated to the persistent worker
        # subprocess.
        needs_qt = detection == 'manual' or refinement == 'manual'

        if needs_qt:
            # Build the request payload for the interactive worker.
            # Only include optional paths when they are actually provided.
            worker_kwargs = dict(
                eld_path=self._eld_path,
                detection=detection,
                refinement=refinement,
                icut=icut,
            )

            if in_file:
                worker_kwargs['in_file'] = str(in_file)
            if out_file:
                worker_kwargs['out_file'] = str(out_file)

            # Run the interactive center operation.
            # _call_worker raises on failure. If the user aborts,
            # it raises the "__CANCELLED__" sentinel wrapped
            # in RuntimeError, which the GUI error handling treats
            # as a cancellation rather than a real error. On success,
            # the worker returns [x, y].

            cx, cy = self._call_worker('center', worker_kwargs)

            # Create or refresh EDIFF's internal CenterLocator-like
            # object. This makes sure self.eld.center exists and has
            # the structure expected by downstream EDIFF plotting and
            # processing code.

            self.eld.find_center(
                detection=None,
                refinement=None,
                icut=icut,
                cmap=cmap,
                csquare=csquare,
                in_file=(
                    str(out_file)
                    if out_file and Path(str(out_file)).exists()
                    else None
                ),
                final_print=False,
            )

            # Override the backend-created center with the exact
            # interactive result.
            if self.eld.center is not None:
                self.eld.center.x  = round(float(cx), 1)
                self.eld.center.y  = round(float(cy), 1)
                self.eld.center.x2 = round(float(cx), 1)
                self.eld.center.y2 = round(float(cy), 1)
        else:
            # Fully automatic / non-interactive center detection.
            # These methods can run in-process because they do not
            # require a Qt point-selection window.
            kwargs = dict(
                detection=detection,
                refinement=refinement,
                icut=icut,
                cmap=cmap,
                csquare=csquare,
                cintensity=cintensity,
                rtype=rtype,
                heq=heq,
                sobel=sobel,
                masking=masking,
                normalize_bg=normalize_bg,
                live_plot=live_plot,
                verbose=1,
                final_print=False,
            )

            # Optional input/output center-file paths.
            if in_file:
                kwargs['in_file'] = str(in_file)

            if out_file:
                kwargs['out_file'] = str(out_file)

            # Let EDIFF perform the actual center detection.
            self.eld.find_center(**kwargs)


