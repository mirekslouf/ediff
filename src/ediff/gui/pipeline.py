    def _save_center_to_file(self, path):
        """
        Write the currently selected center coordinates
        to a center file.

        The file is written in the format expected by EDIFF/background
        tools:

        ``x1: value, y1: value``
        ``x2: value, y2: value``

        This helper is mainly used before interactive background
        subtraction, so the background-picking worker receives
        the same center that the user accepted in the GUI.

        Parameters
        ----------
        path : str or pathlib.Path
            Destination file path.

        Returns
        -------
        None
            Writes the center file if a center exists. Silently
            does nothing if the center is unavailable.
        """
        try:
            c = self.eld.center

            # If center detection has not happened yet, there is
            # nothing to write.
            if c is None:
                return

            # Prefer x/y, but fall back to x2/y2 if necessary.
            x = float(getattr(c, 'x', getattr(c, 'x2', 0)))
            y = float(getattr(c, 'y', getattr(c, 'y2', 0)))

            # Write both x1/y1 and x2/y2 to satisfy EDIFF's expected
            # format.
            with open(path, 'w') as f:
                f.write(f"x1: {x:.4f}, y1: {y:.4f}\n")
                f.write(f"x2: {x:.4f}, y2: {y:.4f}\n")

        except Exception:
            # If the center is missing or shaped unexpectedly, leave it
            # to the interactive background workflow to handle/report
            # the problem.
            pass  #

    # ── Step 6: Background ────────────────────────────────────────────────────
    def subtract_background(self, method, bkg_file):
        """
        Subtract background from the 1D ELD diffractogram.

        The selected method determines how the background is estimated
        or restored.

        Method behavior
        ---------------
        ``InteractivePlot``
            Opens the interactive worker for manual background-point
            picking. The clicked points are written to ``bkg_file``.
            The actual subtraction is then performed using
            ``RestoreFromPoints``.

        ``RestoreFromPoints``
            Restores background points from ``bkg_file`` and subtracts
            the background.

        Other methods
            Treated as non-interactive SimpleFuncs/Baselines methods.
            These do not use ``bkg_file``.

        Implementation note
        -------------------
        The underlying background code has a bug where ``BkgParams(xlim=None)``
        can create ``[0, None]``, which later causes ``plt.xlim([0, None])``
        to raise ``TypeError``. To avoid that, this method passes a concrete
        x-limit derived from the actual pixel range whenever possible.

        Parameters
        ----------
        method : str
            Background-subtraction method name.

        bkg_file : str or pathlib.Path
            Background-point file path used by ``InteractivePlot`` and
            ``RestoreFromPoints``.

        Returns
        -------
        None
            Updates ``self.smet`` and mutates ``self.eld.diffractogram``
            according to the selected background subtraction.
        """
        # Determine the actual pixel range from the current 1D
        # diffractogram. Fall back to 500 if the diffractogram is
        # unavailable or malformed.
        try:
            px = self.eld.diffractogram['Pixels']
            px_max = int(px.max())
        except Exception:
            px_max = 500

        # Interactive background selection needs the accepted center.
        # Write it to center.txt so the interactive background worker
        # uses the same center as the current GUI/pipeline state.
        if method == 'InteractivePlot':
            center_file = str(self.workdir / 'center.txt')
            self._save_center_to_file(center_file)

            # Ask the interactive worker to collect background points.
            # The worker writes those points to bkg_file.
            self._call_worker('bkg', dict(
                eld_path=self._eld_path,
                center_file=center_file,
                bkg_file=str(bkg_file),
            ))

            # Once points are saved, run the actual subtraction in-process
            # by restoring from the point file.
            self.smet = self.eld.subtract_background(
                'RestoreFromPoints', bkg_file=str(bkg_file))

        elif method == 'RestoreFromPoints':
            # Non-interactive restoration from an existing points file.
            self.smet = self.eld.subtract_background(
                method, bkg_file=str(bkg_file))

        else:
            # SimpleFuncs / Baselines methods.
            # Pass a concrete xlim to avoid the backend bug caused
            # by xlim=None.
            self.smet = self.eld.subtract_background(
                method, xlim=[0, px_max])

    def plot_background(self, xlim=(0, 500), ylim=None):
        """
        Plot background-subtraction diagnostics.

        Three plots are returned:

        1. Original 1D diffractogram.
        2. Diffractogram with estimated background.
        3. Background-subtracted diffractogram.

        Parameters
        ----------
        xlim : tuple or None, optional
           Pixel-axis limits applied to each plot.

        ylim : tuple or None, optional
           Optional intensity-axis limits applied to each plot.

        Returns
        -------
        list of io.BytesIO
           PNG buffers for the original, with-background, and without-
           background plots. Returns an empty list if background subtraction
           has not been run.
        """
        # Background subtraction has not run yet.
        if self.smet is None:
            return []

        bufs = []

        # Plot each diagnostic view provided by the background-subtraction
        # object.
        for plot_fn in [
            self.smet.plots.plot_original,
            self.smet.plots.plot_with_bkg,
            self.smet.plots.plot_without_bkg,
        ]:
            try:
                plot_fn()
            except Exception:
                # Even if one plot function fails internally, still attempt
                # to capture whatever figure exists and continue to the next
                # plot.
                pass

            # Apply shared pixel/intensity axis limits.
            if xlim: plt.xlim(xlim)
            if ylim: plt.ylim(ylim)

            # Capture the current figure and close it.
            bufs.append(_capture_fig())
        return bufs

    # ── Step 7: Calibrate ─────────────────────────────────────────────────────
    def calibrate(self, method='MaxPeaks', ref_phase_idx=0, **kwargs):
        """
        Calibrate the experimental ELD profile from pixel units
        to q-space.

        This method updates the current ELD diffractogram so that
        its radial pixel coordinate is converted to scattering vector
        ``q`` and its intensity is normalized. The calibrated ELD
        profile can then be compared directly with theoretical XRD
        diffractograms.

        Two calibration families are supported:

        1. Microscope / MicroscopeParams
           Compute the calibration constant directly from microscope
           geometry: accelerating voltage, camera length, camera pixel
           size, and binning.

        2. Peak-based methods
           Delegate calibration to EDIFF's ``calibrate_and_normalize``
           method, using a selected XRD phase as the reference.

        Parameters
        ----------
        method : str, optional
            Calibration method name. Supported GUI values include
            ``"MaxPeaks"``, ``"MaxPeaksInRange"``, ``"Microscope"``,
            and ``"MicroscopeParams"``.

        ref_phase_idx : int, optional
            Index of the XRD phase in ``self.xrd_list`` used as the
            calibration reference for peak-based methods.

        **kwargs
            Additional calibration parameters. For ``"Microscope"``
            and ``"MicroscopeParams"``, the relevant keys are:

            - ``voltage_kV``
            - ``camera_length_mm``
            - ``camera_pixel_size_um``
            - ``binning``

            For peak-based methods, any keyword arguments are passed
            through to `self.eld.calibrate_and_normalize``.

        Returns
        -------
        None
            Mutates ``self.eld.diffractogram`` in place by adding/
            updating q-space calibration and normalized intensity.
        """
        # Reference XRD phase used by peak-based calibration methods.
        # For microscope-parameter calibration this is retrieved but
        # not used.
        ref_xrd = self.xrd_list[ref_phase_idx]

        if method in ('Microscope', 'MicroscopeParams'):
            # Compute the pixel-to-q calibration constant from microscope
            # geometry. Calibrate.from_microscope expects a predefined
            # microscope object or microscope name. Here the GUI provides
            # explicit microscope parameters, so both "Microscope" and
            # "MicroscopeParams" are routed to  from_microscope_params().
            const = self.ed.calibration.Calibrate.from_microscope_params(
                voltage_kV           = kwargs.get(
                    'voltage_kV',
                    120
                ),
                camera_length_mm     = kwargs.get(
                    'camera_length_mm',
                    170
                ),
                camera_pixel_size_um = kwargs.get(
                    'camera_pixel_size_um',
                    13.2
                ),
                binning              = kwargs.get(
                    'binning',
                    2
                ),
                verbose              = False,
            )

            # Store the calibration constant on the ELD object for
            # later reference.
            self.eld.calibration_constant = const

            # Ensure the diffractogram has a q column.
            # If not present, insert it after the first column.
            if 'q' not in self.eld.diffractogram.columns:
                self.eld.diffractogram.insert(
                    loc=1,
                    column='q',
                    value=1
                )

            # Convert pixel radius to q using the calculated constant.
            self.eld.diffractogram.q = self.eld.diffractogram.Pixels*const

            # Normalize ELD intensity to its maximum value.
            # This mirrors the normalization done by calibrate_and_normalize().
            imax = np.max(self.eld.diffractogram.I)
            if imax == 0 or not np.isfinite(imax):
                raise ValueError(
                    "Cannot normalize ELD intensity: maximum intensity is zero or invalid."
                )
            self.eld.diffractogram.I = self.eld.diffractogram.I / imax

        else:
            # Peak-based calibration.
            # MaxPeaks / MaxPeaksInRange and similar methods are handled
            # directly by EDIFF. They use the selected XRD phase as reference.
            self.eld.calibrate_and_normalize(
                method,
                ref_xrd,
                **kwargs
            )

    def plot_final_comparison(self, fine_tune=1.003, xlim=(1, 8), ylim=None,
                               phase_idx=0, out_file=None):
        """
        Plot calibrated ELD against one selected XRD phase.

        This is a thin wrapper around EDIFF's own
        ``plot_final_eld_and_xrd`` plotting function. It generates
        an ELD-vs-XRD comparison plot, optionally saves it to disk,
        captures the matplotlib figure as an in-memory PNG buffer,
        and closes the figure.

        Parameters
        ----------
        fine_tune : float, optional
            Multiplicative fine-tuning factor applied to the ELD q-axis
            during plotting. This lets the user make small manual alignment
            adjustments without recalibrating the underlying data.

        xlim : tuple, optional
            q-axis limits for the comparison plot.

        ylim : tuple or None, optional
            Optional intensity-axis limits applied after the EDIFF plot
            is created.

        phase_idx : int, optional
            Index of the XRD phase in ``self.xrd_list`` to compare
            against.

        out_file : str or pathlib.Path or None, optional
            Optional path where EDIFF should save the comparison plot.

        Returns
        -------
        io.BytesIO
            PNG buffer containing the rendered comparison plot.
        """
        # Select the requested XRD reference phase.
        xrd = self.xrd_list[phase_idx]

        # Use EDIFF's native final-comparison plot.
        self.ed.io.Plots.plot_final_eld_and_xrd(
            eld_profile=self.eld.diffractogram,
            xrd_profile=xrd.diffractogram,
            fine_tune=fine_tune,
            Xlim=xlim,
            eld_data_label=self.eld.description or 'ED experiment',
            xrd_data_label=xrd.description or 'XRD calculation',
            out_file=str(out_file) if out_file else None,

            # Keep CLI=True because this is the mode expected by
            # the EDIFF plotting helper for direct/non-notebook
            # figure generation.
            CLI=True,
        )
        # Apply optional y-axis limits after the backend plot is
        # created.
        if ylim: plt.ylim(ylim)

        # Capture the current figure as PNG and close it.
        return _capture_fig()

    def plot_all_phases_comparison(self, fine_tune=1.003, xlim=(1, 8), ylim=None,
                                    out_file=None):
        """
        Plot calibrated ELD together with all calculated XRD phases.

        EDIFF's existing multi-comparison helper is oriented toward
        one XRD pattern and multiple ELD profiles. This GUI needs
        the opposite: one ELD profile compared with multiple XRD
        reference phases. Therefore, this method builds the multi-XRD
        overlay directly using matplotlib.

        If only one XRD phase exists, this method delegates to
        ``plot_final_comparison``.

        Parameters
        ----------
        fine_tune : float, optional
            Multiplicative fine-tuning factor applied to the ELD q-axis
            during plotting.

        xlim : tuple, optional
            q-axis limits for the plot.

        ylim : tuple or None, optional
            Optional intensity-axis limits.

        out_file : str or pathlib.Path or None, optional
            Optional path where the combined comparison plot should
            be saved.

        Returns
        -------
        io.BytesIO
            PNG buffer containing the rendered all-phases comparison
            plot.
        """
        # For a single phase, reuse the normal ELD-vs-one-XRD comparison
        # path.
        if len(self.xrd_list) == 1:
            return self.plot_final_comparison(
                fine_tune=fine_tune,
                xlim=xlim,
                ylim=ylim,
                out_file=out_file
            )

        # Fixed color cycle for XRD phases.
        colors = [
            'tab:blue',
            'tab:orange',
            'tab:green',
            'tab:purple',
            'tab:brown',
            'tab:pink'
        ]
        # Plot all XRD reference phases.
        for i, xrd in enumerate(self.xrd_list):
            d = xrd.diffractogram

            plt.plot(
                d.q,
                d.I,
                color=colors[i % len(colors)],
                label=xrd.description or f'XRD phase {i+1}'
            )

        # Plot calibrated ELD profile with optional fine-tune scaling.
        eld_d = self.eld.diffractogram


        plt.plot(
            eld_d.q * fine_tune,
            eld_d.I,
             color='red',
            label=self.eld.description or 'ED experiment'
        )

        # Apply plot formatting.
        plt.xlim(xlim)

        if ylim: plt.ylim(ylim)

        plt.xlabel(r'$q$ [1/Å]')
        plt.ylabel('Intensity')
        plt.legend()
        plt.grid()
        plt.tight_layout()

        # Optionally save the plot to disk.
        if out_file:
            plt.savefig(str(out_file), dpi=300, facecolor='white')

        # Capture figure as PNG buffer and close it
        return _capture_fig()

    # ── Save ──────────────────────────────────────────────────────────────────
    def save_all(self, fine_tune=1.003, xlim=(1, 8)):
        """
        Save final comparison plots and diffractogram text files
        to the workdir.

        This backend save routine writes:

        - one ELD-vs-XRD comparison PNG per XRD phase;
        - one combined all-phases comparison PNG;
        - one text file per calculated XRD diffractogram;
        - one text file for the calibrated ELD diffractogram.

        Files are saved into ``self.workdir``. The GUI may later copy
        these files to  a user-selected output directory.

        Parameters
        ----------
        fine_tune : float, optional
            Multiplicative fine-tuning factor applied to ELD q-values
            for plotting and ELD diffractogram export.

        xlim : tuple, optional
            q-axis limits used for saved comparison plots.

        Returns
        -------
        None
            Writes output files into ``self.workdir``.
        """
        # Use pipeline working directory as the output location.
        out = self.workdir

        # Save one comparison plot for each XRD phase using EDIFF's
        # comparison helper. compare_with_XRD writes directly to out_file.
        for i, xrd in enumerate(self.xrd_list):
            self.eld.compare_with_XRD(
                xrd, fine_tune=fine_tune, Xlim=xlim,
                out_file=str(out / f'comparison_phase{i+1}.png'),
            )
            # Close any figures left open by compare_with_XRD.
            plt.close('all')

        # Save combined overlay of ELD with all XRD phases.
        self.plot_all_phases_comparison(
            fine_tune=fine_tune, xlim=xlim,
            out_file=out / 'comparison_all_phases.png')

        # Save each theoretical XRD diffractogram as text.
        for i, xrd in enumerate(self.xrd_list):
            xrd.diffractogram.save(
                str(
                    out / f'xrd_phase{i+1}.txt'
                )
            )

        # Save calibrated ELD diffractogram as text.
        self.eld.diffractogram.save(
            str(out / 'eld_diffractogram.txt'),
            fine_tune=fine_tune
        )